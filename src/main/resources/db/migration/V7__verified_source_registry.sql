CREATE TABLE source_verification_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_url TEXT NOT NULL,
    origin VARCHAR(32) NOT NULL,
    claimed_employer_domain VARCHAR(253),
    official_page_url TEXT,
    observed_url TEXT,
    observed_at TIMESTAMPTZ NOT NULL,
    method_version VARCHAR(32) NOT NULL,
    outcome VARCHAR(32) NOT NULL,
    reason VARCHAR(64),
    platform VARCHAR(32),
    region VARCHAR(16),
    source_id VARCHAR(64),
    evidence_hash CHAR(64) NOT NULL,
    requests INTEGER NOT NULL CHECK (requests BETWEEN 0 AND 3),
    UNIQUE (candidate_url, evidence_hash)
);

CREATE TABLE verified_source_registry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform VARCHAR(32) NOT NULL,
    region VARCHAR(16) NOT NULL,
    source_id VARCHAR(64) NOT NULL,
    employer_domain VARCHAR(253) NOT NULL,
    employer_name VARCHAR(255) NOT NULL,
    official_page_url TEXT NOT NULL,
    evidence_url TEXT NOT NULL,
    evidence_hash CHAR(64) NOT NULL,
    verified_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(32) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (platform, region, source_id)
);

CREATE INDEX verified_source_registry_active_idx ON verified_source_registry (active, verified_at);
