CREATE TABLE scheduled_batch_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_date DATE NOT NULL UNIQUE,
    status VARCHAR(24) NOT NULL CHECK (status IN ('RUNNING', 'PREPARED', 'PUBLISHING', 'PUBLISHED', 'FAILED', 'UNCERTAIN')),
    profile_id VARCHAR(128) NOT NULL,
    profile_version VARCHAR(64) NOT NULL,
    report_text TEXT,
    sns_message_id VARCHAR(128),
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ,
    CONSTRAINT scheduled_batch_report_text_bound CHECK (report_text IS NULL OR octet_length(report_text) <= 12000)
);

CREATE UNIQUE INDEX scheduled_batch_one_active ON scheduled_batch_reports ((1))
    WHERE status IN ('RUNNING', 'PREPARED', 'PUBLISHING');
